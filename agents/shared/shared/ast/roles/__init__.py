"""``shared.ast.roles``: the role lexicons, the two identifier normalisers, the prefilter and the
role predicates of the AST layer (feature 0102, LLD §8.3, §8.5, §9.1; A10, A21, A27).

Every §9.1 table, with ``COVERED_BY`` and ``COVERING_GUARDS`` (§8.3), is defined ONCE, in a
module of this package, and re-exported here: ``flow`` imports them, never a copy (A27 (5)).
Three kinds of lexicon, never mixed (L1 as restated by P1), each lookup one O(1) probe:

* SINK-SIDE callee lexicons (``sinks``, and the structural keys of ``sources``) are stored
  GLUED and matched by ``glue`` of the callee's last identifier;
* GUARD and SANITISER role lexicons (``guards``, ``sanitizers``) are WORD lexicons of generic
  concept words, read through the inverted indexes ``WORD_ROLES`` / ``KEY_ROLES``; the short
  ambiguous words reach a role only as an EXACT key or inside a composition (R4, L12);
* WORD SETS (``sources``: sources, carriers, receivers) are matched on ``words``.

``glue`` and ``words`` (with ``hits`` and ``word_set`` over them) live in ``_words`` (A10), the wire vocabulary (``SHELL_INTERPRETERS``,
``OPERATOR_TOKENS``, the D16 ``IDENTIFIER`` pattern, ``DECLARATION_KEYWORDS``) in ``_validate``:
both re-exported, never redefined. ``model_needed`` lives in ``sinks``, beside ``PREFILTER``
and ``needed_families`` (its several-family form), and ``shared.ast`` exports it (A27 (4)). The predicates take the model first (A21):
``sanitizer_roles(model, call)``, ``guard_roles(model, test)``, ``host_allow(model, node)``.
"""

